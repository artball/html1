def cards(items, cols=3):
    out = []
    for i, (icon, title, text) in enumerate(items):
        d = f' reveal-delay-{i%3+1}' if i >= 3 else ''
        out.append(f'''          <article class="card card-hover reveal{d}">
            <div class="card-icon">{icon}</div>
            <h3>{title}</h3>
            <p class="text-soft small">{text}</p>
          </article>''')
    return f'''    <section class="section">
      <div class="container">
        <div class="grid-{cols}">
{chr(10).join(out)}
        </div>
      </div>
    </section>
'''

def steps_section(num_label, h2, lead, steps, alt=True):
    items = "\n".join(f'          <div class="step"><h3>{t}</h3><p>{d}</p></div>' for t, d in steps)
    return f'''    <section class="section{' section-alt' if alt else ''}" aria-labelledby="{num_label}-h">
      <div class="container grid-2">
        <div class="reveal">
          <p class="section-num">// {h2[0]}</p>
          <h2 id="{num_label}-h">{h2[1]}</h2>
          <p class="lead">{lead}</p>
        </div>
        <div class="steps reveal reveal-delay-1">
{items}
        </div>
      </div>
    </section>
'''

def prose_section(h2, paras, alt=False, extra=''):
    body = "\n        ".join(f'<p>{p}</p>' if isinstance(p, str) else p for p in paras)
    return f'''    <section class="section prose{' section-alt' if alt else ''}">
      <div class="container" style="max-width:880px">
        <h2>{h2}</h2>
        <div class="stack">
        {body}
        {extra}
        </div>
      </div>
    </section>
'''

